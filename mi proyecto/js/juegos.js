document.addEventListener("DOMContentLoaded", () => {
    const filas = document.querySelectorAll("tbody tr");
    const contenedorDetalle = document.getElementById("detalle-juego");

    if (!contenedorDetalle) return;

    filas.forEach(fila => {
        fila.addEventListener("click", () => {
            const idJuego = fila.getAttribute("data-id");
            const juego = infoJuegos[idJuego];

            if (juego) {
                contenedorDetalle.innerHTML = `
                    <img src="${juego.imagen}" alt="Portada de ${juego.titulo}">
                    <div class="info-texto">
                        <h3>${juego.titulo} (${juego.anio})</h3>
                        <p><strong>Plataforma:</strong> ${juego.consola}</p>
                        <p>${juego.descripcion}</p>
                    </div>
                `;
            }
        });
    });
});